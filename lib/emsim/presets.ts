// The 2-layer board: one FR-4 core, εr 4.5 (U3). JLCPCB states no core thickness for it: 1.6 mm less the two copper
// layers, an assumption the source says.
function twoLayer(): Stackup {
  const s = build({ id: 'JLC-2L-1.6', name: 'JLCPCB 2 layers, 1.6 mm, 1 oz', file: '', half: [O, { core: 1.53 }] });
  const core = s.layers[2] as DielectricLayer;
  core.material = 'FR-4';
  core.name = 'Core FR-4';
  core.t = v(1.53, src(s.id, 'U1', 'JLCPCB states no core thickness for 2-layer boards: 1.6 mm board less 2 × 0.035 mm copper (assumed)'));
  core.er = v(4.5, src(s.id, 'U3'));
  return s;
}

const BUILT: Stackup[] = [...DEFS.map(build), twoLayer()];
// The GsuberlandStackups file each preset's thicknesses come from, as the source's URL.
for (const s of BUILT) {
  const def = DEFS.find((d) => d.id === s.id);
  if (!def) continue;
  const url = `${REFS.G.url}/blob/main/raw_json/${def.file}`;
  for (const l of s.layers) if (l.kind !== 'mask' && l.t.src.kind === 'preset' && l.t.src.ref === 'G') l.t = { ...l.t, src: { ...l.t.src, url } };
}

export const PRESET_IDS: readonly string[] = BUILT.map((s) => s.id);

// The URL a preset number from reference `ref` carries (G: the preset's own data file), '' for an unknown reference.
export function refUrl(ref: string, presetId: string): string {
  if (ref === 'G') {
    const def = DEFS.find((d) => d.id === presetId);
    if (def) return `${REFS.G.url}/blob/main/raw_json/${def.file}`;
  }
  return REFS[ref]?.url ?? '';
}

// The preset's stackup as a fresh copy (editing it never changes the table), or null for an unknown id.
export function presetStackup(id: string): Stackup | null {
  const s = BUILT.find((p) => p.id === id);
  return s ? (JSON.parse(JSON.stringify(s)) as Stackup) : null;
}

