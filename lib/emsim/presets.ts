export const PRESET_IDS: readonly string[] = BUILT.map((s) => s.id);

// Each preset's entry in jlcpcbStackups.json, by preset id (M1.8c lists these first).
export const PRESET_KEYS: Readonly<Record<string, string>> = Object.fromEntries(DEFS.map((d) => [d.id, d.key]));

// The URL a preset number from reference `ref` carries (G: the preset's former data file), '' for an unknown reference.
export function refUrl(ref: string, presetId: string): string {
  if (ref === 'G') {
    const def = DEFS.find((d) => d.id === presetId);
    if (def && def.file) return `${REFS.G.url}/blob/main/raw_json/${def.file}`;
  }
  return REFS[ref]?.url ?? '';
}

// The preset's stackup as a fresh copy (editing it never changes the table), or null for an unknown id.
export function presetStackup(id: string): Stackup | null {
  const s = BUILT.find((p) => p.id === id);
  return s ? (JSON.parse(JSON.stringify(s)) as Stackup) : null;
}

