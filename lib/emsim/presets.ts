// JLCPCB's published stackups as presets (docs/em-sim/facts-fab.md §1), every number with the reference it was read
// from, the date it was read and its URL. Thicknesses (as pressed: prepreg after the fill of the copper next to it) and
// εr are JLCPCB's own, as its impedance calculator's API gave them on 2026-11-16 (A; notes-M1.8b.md); mask, copper as
// the calculator counts it and the trapezoid from the calculator's parameters (U1, U2). JLCPCB states no frequency for
// its εr and no loss tangent: both stay "not stated" (notes-M0.2b.md). The same stackups are entries of
// jlcpcbStackups.json; check-jlcpcb.mjs keeps every preset here equal, layer by layer, to `jlcStackup` of its entry.

import type { CopperLayer, DielectricLayer, Layer, MaskLayer, Source, Stackup, Val } from './stackup';

export const READ_DATE = '2026-11-16';

// The references the presets cite, by key (the link writes a preset number's source as the key).
export const REFS: Readonly<Record<string, { url: string; what: string }>> = {
  A: { url: 'https://jlcpcb.com/pcb-impedance-calculator', what: 'JLCPCB impedance calculator’s stackup templates (its API, fetched 2026-11-16): thicknesses and εr' },
  U1: { url: 'https://jlcpcb.com/impedance', what: 'JLCPCB impedance page: stackups, mask parameters, copper' },
  U2: { url: 'https://jlcpcb.com/help/article/User-Guide-to-the-JLCPCB-Impedance-Calculator', what: 'JLCPCB calculator guide: εr tables, copper, mask, trace top width' },
  U3: { url: 'https://jlcpcb.com/capabilities/pcb-capabilities', what: 'JLCPCB capabilities: FR-4 εr of 2-layer boards' },
  G: { url: 'https://github.com/gsuberland/jlcpcb_autogenerated_stackups', what: 'JLCPCB’s impedance-template API data (2025-05-09), raw_json' },
  S: { url: 'https://jlcpcb.com/pcb-impedance-calculator', what: 'JLCPCB’s online calculator (Polar Si9000): the inputs it sends, used by “as JLCPCB’s calculator”' },
};

export function presetSrc(id: string, ref: string, date = READ_DATE, note?: string): Source {
  const r = REFS[ref];
  return note ? { kind: 'preset', id, ref, date, url: r.url, note } : { kind: 'preset', id, ref, date, url: r.url };
}

const v = (x: number, s: Source): Val => ({ v: x, tol: null, src: s });

export const MIL = 0.0254;

// The solder mask of every JLCPCB stackup: C1, C2, C3 and εr 3.8 (U1, U2 agree).
export function jlcMask(id: string, mid: string, name: string, date = READ_DATE): MaskLayer {
  const page = presetSrc(id, 'U1', date);
  return {
    kind: 'mask', id: mid, name, material: 'LPI solder mask',
    er: v(3.8, page), tand: null, freq: null,
    onLaminate: v(1.2 * MIL, page), onCopper: v(0.6 * MIL, page), between: v(1.2 * MIL, page),
  };
}

// The thickness JLCPCB's calculator counts for a copper layer (U2's parameter table), null where it states none:
// outer 1 oz 1.6 mil; inner ½ oz (0.0152 mm) 0.6 mil, inner 1 oz (0.03 mm) 1.2 mil.
export function jlcCalc(outer: boolean, oz: number | null, t: number): number | null {
  if (outer) return oz === 1 ? 1.6 * MIL : null;
  if (Math.abs(t - 0.0152) < 1e-9) return 0.6 * MIL;
  if (Math.abs(t - 0.03) < 1e-9) return 1.2 * MIL;
  return null;
}

// A copper layer: the API's thickness, the calculator's, the etch of 0.35 mil per side (U2: top = base − 0.7 mil).
export function jlcCopper(id: string, t: number, calc: number | null, date = READ_DATE): CopperLayer {
  const guide = presetSrc(id, 'U2', date);
  return {
    kind: 'copper', id: '', name: '', t: v(t, presetSrc(id, 'A', date)), base: null, plating: null,
    calc: calc === null ? null : v(calc, guide), etch: { kind: 'offset', side: v(0.35 * MIL, guide) }, fill: null,
  };
}

export function jlcDielectric(id: string, role: 'core' | 'prepreg', material: string, t: number, er: number, date = READ_DATE): DielectricLayer {
  const api = presetSrc(id, 'A', date);
  return { kind: 'dielectric', id: '', name: '', role, material, t: v(t, api), er: v(er, api), tand: null, freq: null };
}

// Ids and names of the layers between the masks, top to bottom, then the masks around them.
export function jlcFinish(id: string, name: string, inner: Layer[], date = READ_DATE): Stackup {
  let cu = 0;
  let di = 0;
  const n = inner.filter((l) => l.kind === 'copper').length;
  for (const l of inner) {
    if (l.kind === 'copper') {
      cu += 1;
      l.id = `L${cu}`;
      l.name = cu === 1 ? 'L1 (top)' : cu === n ? `L${cu} (bottom)` : `L${cu}`;
    } else if (l.kind === 'dielectric') {
      di += 1;
      l.id = `D${di}`;
      l.name = `${l.role === 'core' ? 'Core' : 'Prepreg'} ${l.material}`;
    }
  }
  return { id, name, layers: [jlcMask(id, 'MT', 'Top mask', date), ...inner, jlcMask(id, 'MB', 'Bottom mask', date)], finish: '', controlled: true, thickness: null };
}

// One layer of a preset's top half: copper ('o' outer or 'i' inner), a prepreg of a glass style, a core (NP-155F) or
// a core whose copper is etched off.
type Spec = { cu: 'o' | 'i'; t: number } | { pp: string; t: number; er: number } | { core: number; er: number; bare?: true };

interface PresetDef {
  id: string;
  key: string; // its entry in jlcpcbStackups.json (jlcKey)
  name: string;
  file: string; // GsuberlandStackups raw_json file it was read from before M1.8b (refUrl of ref G, for old links)
  half: Spec[]; // top copper to the centre layer (which is not repeated)
}

const NP = 'NP-155F';

function build(def: PresetDef): Stackup {
  const { id } = def;
  const half: Layer[] = def.half.map((s) => {
    if ('cu' in s) return jlcCopper(id, s.t, jlcCalc(s.cu === 'o', s.cu === 'o' ? 1 : null, s.t));
    if ('pp' in s) return jlcDielectric(id, 'prepreg', s.pp, s.t, s.er);
    return jlcDielectric(id, 'core', s.bare ? `FR-4 core, etched bare (${NP})` : `FR-4 core (${NP})`, s.core, s.er);
  });
  const all: Layer[] = [...half];
  for (let i = half.length - 2; i >= 0; i -= 1) all.push(JSON.parse(JSON.stringify(half[i])) as Layer);
  return jlcFinish(id, def.name, all);
}

