// JLCPCB's published stackups as presets (docs/em-sim/facts-fab.md §1), every number with the reference it was read
// from, the date it was read and its URL. Thicknesses are JLCPCB's own API data as kept by GsuberlandStackups (data of
// 2025-05-09; facts-fab.md §1.4 says to prefer it over the page text, which differs in two centre layers); εr from the
// calculator guide's tables (by prepreg type and by core thickness); mask, copper and trapezoid from the calculator's
// parameters. JLCPCB states no frequency for its εr and no loss tangent: both stay "not stated" (notes-M0.2b.md).

import type { CopperLayer, DielectricLayer, Layer, MaskLayer, Source, Stackup, Val } from './stackup';

export const READ_DATE = '2026-11-16';

// The references the presets cite, by key (the link writes a preset number's source as the key).
export const REFS: Readonly<Record<string, { url: string; what: string }>> = {
  U1: { url: 'https://jlcpcb.com/impedance', what: 'JLCPCB impedance page: stackups, mask parameters, copper' },
  U2: { url: 'https://jlcpcb.com/help/article/User-Guide-to-the-JLCPCB-Impedance-Calculator', what: 'JLCPCB calculator guide: εr tables, copper, mask, trace top width' },
  U3: { url: 'https://jlcpcb.com/capabilities/pcb-capabilities', what: 'JLCPCB capabilities: FR-4 εr of 2-layer boards' },
  G: { url: 'https://github.com/gsuberland/jlcpcb_autogenerated_stackups', what: 'JLCPCB’s impedance-template API data (2025-05-09), raw_json' },
};

function src(id: string, ref: string, note?: string): Source {
  const r = REFS[ref];
  return note ? { kind: 'preset', id, ref, date: READ_DATE, url: r.url, note } : { kind: 'preset', id, ref, date: READ_DATE, url: r.url };
}

const v = (x: number, s: Source): Val => ({ v: x, tol: null, src: s });

const MIL = 0.0254;

// Prepreg εr (U2's table; U1 and U3 agree).
const PREPREG_ER: Readonly<Record<string, number>> = { '7628': 4.4, '3313': 4.1, '1080': 3.91, '2116': 4.16 };

// Core εr by thickness in mm (U2's table image).
export function coreEr(t: number): number {
  const r = Math.round(t * 1000) / 1000;
  if (r > 0.7) return 4.43;
  const table: ReadonlyArray<readonly [number, number]> = [
    [0.08, 3.99], [0.1, 4.36], [0.13, 4.17], [0.15, 4.36], [0.2, 4.36], [0.25, 4.23], [0.3, 4.41], [0.35, 4.36],
    [0.4, 4.36], [0.45, 4.36], [0.5, 4.48], [0.55, 4.41], [0.6, 4.36], [0.65, 4.36], [0.7, 4.53],
  ];
  for (const [tt, er] of table) if (Math.abs(tt - r) < 1e-9) return er;
  return NaN;
}

// One layer of a preset's top half: copper ('o' outer or 'i' inner with its thickness) or a dielectric.
type Spec =
  | { cu: 'o' | 'i'; t: number }
  | { pp: string; t: number } // prepreg of a glass style ('' when JLCPCB names none)
  | { core: number };

interface PresetDef {
  id: string;
  name: string;
  file: string; // GsuberlandStackups raw_json file name ('' for the 2-layer board)
  half: Spec[]; // top copper to the centre layer (which is not repeated)
}

function build(def: PresetDef): Stackup {
  const id = def.id;
  const thick = def.file ? src(id, 'G') : src(id, 'U1');
  const guide = src(id, 'U2');
  const page = src(id, 'U1');
  const mask = (mid: string, name: string): MaskLayer => ({
    kind: 'mask', id: mid, name, material: 'LPI solder mask',
    er: v(3.8, page), tand: null, freq: null,
    onLaminate: v(1.2 * MIL, page), onCopper: v(0.6 * MIL, page), between: v(1.2 * MIL, page),
  });
  const half: Layer[] = [];
  const sequence = [...def.half];
  for (const s of sequence) {
    if ('cu' in s) {
      const calc = s.cu === 'o' ? 1.6 * MIL : s.t > 0.02 ? 1.2 * MIL : 0.6 * MIL;
      const c: CopperLayer = {
        kind: 'copper', id: '', name: '', t: v(s.t, thick), base: null, plating: null, calc: v(calc, guide),
        etch: { kind: 'offset', side: v(0.35 * MIL, guide) }, fill: null,
      };
      half.push(c);
    } else if ('pp' in s) {
      const er = PREPREG_ER[s.pp];
      const d: DielectricLayer = {
        kind: 'dielectric', id: '', name: '', role: 'prepreg', material: s.pp || 'not named', t: v(s.t, thick),
        er: er ? v(er, guide) : v(coreEr(s.t), src(id, 'U2', 'JLCPCB names no material for this layer; εr of a core of this thickness from the guide’s table, as GsuberlandStackups assigns it')),
        tand: null, freq: null,
      };
      half.push(d);
    } else {
      const d: DielectricLayer = {
        kind: 'dielectric', id: '', name: '', role: 'core', material: 'FR-4 core (NP-155F)', t: v(s.core, thick),
        er: v(coreEr(s.core), guide), tand: null, freq: null,
      };
      half.push(d);
    }
  }
  // Mirror: the centre layer once.
  const all: Layer[] = [...half];
  for (let i = half.length - 2; i >= 0; i -= 1) all.push({ ...half[i] } as Layer);
  let cu = 0;
  let di = 0;
  const n = all.filter((l) => l.kind === 'copper').length;
  for (const l of all) {
    if (l.kind === 'copper') {
      cu += 1;
      l.id = `L${cu}`;
      l.name = cu === 1 ? 'L1 (top)' : cu === n ? `L${cu} (bottom)` : `L${cu}`;
    } else {
      di += 1;
      l.id = `D${di}`;
      l.name = `${(l as DielectricLayer).role === 'core' ? 'Core' : 'Prepreg'} ${(l as DielectricLayer).material}`;
    }
  }
  return { id, name: def.name, layers: [mask('MT', 'Top mask'), ...all, mask('MB', 'Bottom mask')], finish: '', controlled: true, thickness: null };
}

