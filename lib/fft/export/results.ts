// Structured result exporters (CSV, JSON, LaTeX booktabs, Markdown)
// Every export includes active conventions and fired diagnostic checks (P12).

import type { AnalysisResult } from '../types';
import { escapeLatex, sanitizeCsvCell } from '../plot/exporters';

function formatConventionsSummary(r: AnalysisResult): Record<string, string | number | boolean> {
  const c = r.setup.conventions;
  return {
    estimator: r.setup.estimator,
    window: r.resolvedWindow,
    fsHz: r.setup.fs,
    n: r.setup.n,
    fullScale: r.setup.fullScale ?? 'none',
    bits: r.setup.bits ?? 'none',
    harmonicsCount: c.harmonicsCount,
    snrExcludesHarmonics: c.snrExcludesHarmonics,
    thdNegativeDb: c.thdNegativeDb,
    enobFsCorrection: c.enobFsCorrection,
    noiseBinCompensation: c.noiseBinCompensation,
    refImpedanceOhm: c.refImpedanceOhm,
    bandHz: r.setup.band ? `${r.setup.band[0]}..${r.setup.band[1]}` : 'full Nyquist',
  };
}

/** Export single analysis metrics, conventions, checks, and harmonics as CSV. */
export function exportResultsCsv(result: AnalysisResult): string {
  const rows: string[] = [];
  rows.push(['Section', 'Key', 'Value', 'Unit', 'Convention'].map(sanitizeCsvCell).join(','));

  const conv = formatConventionsSummary(result);
  for (const [k, v] of Object.entries(conv)) {
    rows.push(['Convention', k, String(v), '', ''].map(sanitizeCsvCell).join(','));
  }

  for (const m of result.metrics) {
    rows.push(
      [
        'Metric',
        m.label,
        m.value !== null && Number.isFinite(m.value) ? String(m.value) : m.formatted,
        m.unit,
        m.convention,
      ]
        .map(sanitizeCsvCell)
        .join(','),
    );
  }

  for (const h of result.harmonics) {
    rows.push(
      [
        'Harmonic',
        `HD${h.order}`,
        h.dbc.toFixed(4),
        'dBc',
        `folded=${h.foldedFreqHz.toFixed(3)}Hz;zone=${h.nyquistZone}${h.overlappedWith ? `;overlap=${h.overlappedWith}` : ''}`,
      ]
        .map(sanitizeCsvCell)
        .join(','),
    );
  }

  for (const chk of result.checks) {
    rows.push(
      ['Check', chk.id, chk.level, '', JSON.stringify(chk.params)].map(sanitizeCsvCell).join(','),
    );
  }

  return rows.join('\n') + '\n';
}

/** Export complete analysis result as structured JSON (metrics + conventions + checks + harmonics). */
export function exportResultsJson(result: AnalysisResult): string {
  const payload = {
    schemaVersion: 1,
    dataset: result.datasetName,
    signal: result.signalLabel,
    unit: result.unit,
    conventions: formatConventionsSummary(result),
    windowMetrics: {
      kind: result.windowMetrics.kind,
      coherentGain: result.windowMetrics.coherentGain,
      enbwBins: result.windowMetrics.enbwBins,
      highestSidelobeDb: result.windowMetrics.highestSidelobeDb,
      scallopingLossDb: result.windowMetrics.scallopingLossDb,
    },
    timeGrid: result.timeGrid,
    resample: result.resample,
    metrics: result.metrics.map((m) => ({
      id: m.id,
      group: m.group,
      label: m.label,
      value: m.value,
      formatted: m.formatted,
      unit: m.unit,
      convention: m.convention,
    })),
    harmonics: result.harmonics,
    topSpurs: result.topSpurs,
    checks: result.checks,
  };
  return JSON.stringify(payload, null, 2) + '\n';
}

/** Export publication-ready LaTeX booktabs table with conventions footnote and checks. */
export function exportResultsLatex(result: AnalysisResult): string {
  const lines: string[] = [
    '% Generated by FFT / Spectrum Analyzer (requires \\usepackage{booktabs})',
    '\\begin{table}[htbp]',
    '\\centering',
    `\\caption{Spectral figures of merit for ${escapeLatex(result.datasetName)} ($N = ${result.setup.n}$, ${escapeLatex(result.resolvedWindow)} window).}`,
    '\\begin{tabular}{llll}',
    '\\toprule',
    'Metric & Value & Unit & Convention \\\\',
    '\\midrule',
  ];

  for (const m of result.metrics) {
    lines.push(
      `${escapeLatex(m.label)} & ${escapeLatex(m.formatted)} & ${escapeLatex(m.unit)} & ${escapeLatex(m.convention)} \\\\`,
    );
  }

  lines.push('\\bottomrule');
  lines.push('\\end{tabular}');
  if (result.checks.length > 0) {
    const checkList = result.checks.map((c) => `${c.id} (${c.level})`).join(', ');
    lines.push(`% Diagnostics triggered: ${escapeLatex(checkList)}`);
  }
  lines.push('\\end{table}');
  return lines.join('\n') + '\n';
}

/** Export Markdown summary table with active conventions and triggered checks. */
export function exportResultsMarkdown(result: AnalysisResult): string {
  const lines: string[] = [
    `# Spectral Analysis — ${result.datasetName}`,
    '',
    `- **Signal**: ${result.signalLabel} (${result.unit})`,
    `- **Window**: ${result.resolvedWindow} (ENBW = ${result.windowMetrics.enbwBins.toFixed(3)} bins)`,
    `- **Record**: N = ${result.setup.n}, fs = ${result.setup.fs} Hz, Estimator = ${result.setup.estimator}`,
    '',
    '| Metric | Value | Unit | Convention |',
    '| --- | ---: | --- | --- |',
  ];

  for (const m of result.metrics) {
    const esc = (s: string) => s.replaceAll('|', '\\|');
    lines.push(`| ${esc(m.label)} | ${esc(m.formatted)} | ${esc(m.unit)} | ${esc(m.convention)} |`);
  }

  if (result.checks.length > 0) {
    lines.push('', '## Diagnostics', '');
    for (const c of result.checks) {
      lines.push(`- **${c.id}** (${c.level}): ${JSON.stringify(c.params)}`);
    }
  }

  return lines.join('\n') + '\n';
}

const BATCH_METRIC_IDS = ['M-FUND', 'M-SNDR', 'M-ENOB', 'M-SNR', 'M-THD', 'M-SFDR', 'M-NF'];

/** Export multi-file comparison table as CSV (spreadsheet-injection safe). */
export function exportBatchCompareCsv(results: AnalysisResult[]): string {
  const header = ['Dataset', 'Window', 'N', 'fs (Hz)', 'f0 (Hz)', 'SNDR (dB)', 'ENOB (bits)', 'SNR (dB)', 'THD (dBc)', 'SFDR (dBc)', 'Noise floor (dBFS)', 'Checks'];
  const rows = [header.map(sanitizeCsvCell).join(',')];

  for (const r of results) {
    const byId = new Map(r.metrics.map((m) => [m.id, m]));
    const vals = BATCH_METRIC_IDS.map((id) => {
      const m = byId.get(id);
      return m?.value !== null && m?.value !== undefined && Number.isFinite(m.value)
        ? m.value.toFixed(4)
        : (m?.formatted ?? '—');
    });
    const checks = r.checks.map((c) => `${c.id}:${c.level}`).join('; ');
    rows.push(
      [r.datasetName, r.resolvedWindow, String(r.setup.n), String(r.setup.fs), ...vals, checks]
        .map(sanitizeCsvCell)
        .join(','),
    );
  }
  return rows.join('\n') + '\n';
}

/** Export multi-file comparison table as LaTeX booktabs. */
export function exportBatchCompareLatex(results: AnalysisResult[]): string {
  const lines: string[] = [
    '\\begin{table}[htbp]',
    '\\centering',
    '\\caption{Multi-file spectral comparison.}',
    '\\begin{tabular}{lrrrrrr}',
    '\\toprule',
    'Dataset & SNDR (dB) & ENOB & SNR (dB) & THD (dBc) & SFDR (dBc) & Window \\\\',
    '\\midrule',
  ];
  for (const r of results) {
    const get = (id: string) => r.metrics.find((m) => m.id === id)?.formatted ?? '--';
    lines.push(
      `${escapeLatex(r.datasetName)} & ${escapeLatex(get('M-SNDR'))} & ${escapeLatex(get('M-ENOB'))} & ${escapeLatex(get('M-SNR'))} & ${escapeLatex(get('M-THD'))} & ${escapeLatex(get('M-SFDR'))} & ${escapeLatex(r.resolvedWindow)} \\\\`,
    );
  }
  lines.push('\\bottomrule', '\\end{tabular}', '\\end{table}');
  return lines.join('\n') + '\n';
}
